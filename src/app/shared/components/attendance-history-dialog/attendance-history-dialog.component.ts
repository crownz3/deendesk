import { Component, Inject, OnInit } from '@angular/core';
import { MAT_DIALOG_DATA, MatDialogRef, MatDialog } from '@angular/material/dialog';
import { firstValueFrom, map, Observable, of } from 'rxjs';
import { AttendanceRecord, AppUser, AttendanceStatus } from '../../../core/models/domain.model';
import { EntityRecord, RepositoryService } from '../../../core/services/repository.service';
import { AuthService } from '../../../core/services/auth.service';
import { QuickAddDialogComponent } from '../quick-add-dialog/quick-add-dialog.component';

import { AttendanceFirestoreService } from '../../../core/services/attendance-firestore.service';

export interface AttendanceHistoryDialogData {
  title: string;
  studentId?: string;
  classPlanId?: string;
  classId?: string;
}

@Component({
  selector: 'app-attendance-history-dialog',
  templateUrl: './attendance-history-dialog.component.html',
  styleUrls: ['./attendance-history-dialog.component.scss'],
  standalone: false
})
export class AttendanceHistoryDialogComponent implements OnInit {
  records$: Observable<(EntityRecord & AttendanceRecord)[]> = of([]);
  teachers: Record<string, EntityRecord> = {};
  isLoading = true;

  constructor(
    @Inject(MAT_DIALOG_DATA) public data: AttendanceHistoryDialogData,
    private dialogRef: MatDialogRef<AttendanceHistoryDialogComponent>,
    private dialog: MatDialog,
    private repo: RepositoryService,
    private auth: AuthService,
    private attendanceFs: AttendanceFirestoreService
  ) {}

  async ngOnInit(): Promise<void> {
    try {
      const profile = await firstValueFrom(this.auth.profile$);

      const teacherList = await firstValueFrom(this.repo.list('users', profile));
      this.teachers = teacherList.reduce((acc, t) => ({ ...acc, [t.id as string]: t }), {} as Record<string, EntityRecord>);

      // Fetch subcollection days if classPlanId is present
      let subcollDays: any[] = [];
      if (this.data.classPlanId) {
        try {
          subcollDays = await this.attendanceFs.getAllDays(this.data.classPlanId);
        } catch (err) {
          console.warn('[AttendanceHistory] Failed fetching subcoll days', err);
        }
      }

      this.records$ = this.repo.list<EntityRecord & any>('attendance', profile).pipe(
        map(records => {
          let filtered = [...subcollDays, ...records];

          // Filter by classPlanId / classId if provided
          if (this.data.classPlanId) {
            filtered = filtered.filter(r => r['classPlanId'] === this.data.classPlanId);
          }
          if (this.data.classId) {
            filtered = filtered.filter(r => r['classId'] === this.data.classId);
          }

          // Extract per-student rows from the one-doc-per-day structure
          const studentRows: any[] = [];
          for (const record of filtered) {
            if (this.data.studentId) {
              if (Array.isArray(record.students)) {
                // New structure: find the student's entry in the students[] array
                const entry = record.students.find((s: any) => s.studentId === this.data.studentId);
                if (entry) {
                  studentRows.push({
                    ...record,           // spread parent doc (has id, date, classPlanId, etc.)
                    status: entry.status,
                    informed: entry.informed ?? null,
                    reason: entry.reason ?? null,
                    lateTime: entry.lateTime ?? null,
                    _studentEntry: entry // keep original for update reference
                  });
                }
              } else if (record.studentId === this.data.studentId) {
                // Backward compat: old flat per-student doc
                studentRows.push(record);
              }
            } else {
              studentRows.push(record);
            }
          }

          // Sort by date descending, deduplicate by date (prefer manual saves)
          studentRows.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());

          const byDate = new Map<string, any>();
          for (const r of studentRows) {
            const existing = byDate.get(r.date);
            if (!existing) {
              byDate.set(r.date, r);
            } else {
              // Prefer manually-saved records over auto-generated
              if (!r['autoGenerated'] && existing['autoGenerated']) {
                byDate.set(r.date, r);
              }
            }
          }

          return Array.from(byDate.values()).sort((a, b) =>
            new Date(b.date).getTime() - new Date(a.date).getTime()
          );
        })
      );
    } catch (e) {
      console.error('Failed to load attendance history', e);
    } finally {
      this.isLoading = false;
    }
  }

  getTeacherName(teacherId?: string): string {
    if (!teacherId) return 'Unknown';
    return String(this.teachers[teacherId]?.['name'] || this.teachers[teacherId]?.['displayName'] || 'Unknown');
  }

  statusIcon(status: string): string {
    switch (status) {
      case 'present': return 'checkmark-circle-outline';
      case 'absent': return 'close-circle-outline';
      case 'late': return 'time-outline';
      case 'leave': return 'calendar-outline';
      default: return 'ellipse-outline';
    }
  }

  async updateStatus(record: any, status: AttendanceStatus, toggleGroup?: any): Promise<void> {
    if (!record.id) return;
    const previousValue = record.status;

    let extraData: Record<string, any> = {};

    if (status === 'absent' || status === 'leave') {
      const result = await firstValueFrom(this.dialog.open(QuickAddDialogComponent, {
        width: '500px',
        data: {
          title: status === 'absent' ? 'Absent Details' : 'Leave Details',
          fields: [
            {
              key: 'informed',
              label: 'Informed?',
              type: 'button-toggle',
              required: true,
              options: [{label: 'Yes', value: 'Yes'}, {label: 'No', value: 'No'}]
            },
            { key: 'reason', label: 'Reason', type: 'textarea' }
          ],
          submitLabel: 'Save'
        }
      }).afterClosed());

      if (result?.value) {
        extraData = result.value;
      } else {
        if (toggleGroup) toggleGroup.value = previousValue || null;
        return;
      }
    } else if (status === 'late') {
      const result = await firstValueFrom(this.dialog.open(QuickAddDialogComponent, {
        width: '500px',
        data: {
          title: 'Late Details',
          fields: [
            { key: 'lateTime', label: 'How much time late? (e.g. 15 mins)', type: 'text', required: true }
          ],
          submitLabel: 'Save'
        }
      }).afterClosed());

      if (result?.value) {
        extraData = result.value;
      } else {
        if (toggleGroup) toggleGroup.value = previousValue || null;
        return;
      }
    } else {
      extraData = { informed: null, reason: null, lateTime: null };
    }

    try {
      const profile = await firstValueFrom(this.auth.profile$);

      if (Array.isArray(record.students) && this.data.studentId) {
        // Patch in subcollection if classPlanId & date are available
        if (record.classPlanId && record.date) {
          try {
            await this.attendanceFs.patchStudentInDay(
              record.classPlanId,
              record.date,
              record.timetableEntryId,
              this.data.studentId,
              { status, ...extraData }
            );
          } catch (e) {
            console.warn('[AttendanceHistory] Subcollection patch fallback', e);
          }
        }
        // Also update top-level doc if record.id exists
        if (record.id) {
          const updatedStudents = record.students.map((s: any) => {
            if (s.studentId === this.data.studentId) {
              return { ...s, status, ...extraData };
            }
            return s;
          });
          try {
            await this.repo.update('attendance', String(record.id), { students: updatedStudents }, profile);
          } catch (e) {
            /* top-level doc might not exist if subcollection only */
          }
        }
        record.status = status;
        Object.assign(record, extraData);
      } else {
        // Backward compat: old flat per-student doc
        await this.repo.update('attendance', String(record.id), { status, ...extraData }, profile);
      }
    } catch (e) {
      console.error('Failed to update attendance history record', e);
      if (toggleGroup) toggleGroup.value = previousValue || null;
    }
  }

  close(): void {
    this.dialogRef.close();
  }
}
