import { Injectable } from '@angular/core';
import { RepositoryService, EntityRecord } from './repository.service';
import { AppUser, ClassPlan, ClassPlanAttendance, ClassPlanException } from '../models/domain.model';
import { where } from 'firebase/firestore';
import { formatDate } from '@angular/common';

@Injectable({ providedIn: 'root' })
export class ClassPlanAttendanceService {
  constructor(private repo: RepositoryService) { }

  async generateAttendanceForPlanDate(classPlan: ClassPlan, date: Date, currentUser: AppUser): Promise<void> {
    const dateKey = this.formatDateKey(date);

    let skippedBecauseException = false;
    let alreadyExists = false;

    try {
      // 1. Check exceptions
      const exceptions = await this.repo.getAllOnce<EntityRecord & ClassPlanException>('classPlanExceptions', currentUser, undefined, [
        where('classPlanId', '==', classPlan.id),
        where('date', '==', dateKey)
      ]);

      const exception = exceptions[0];

      if (exception && ['holiday', 'suddenLeave', 'cancelled'].includes(exception.type)) {
        skippedBecauseException = true;
        console.log('[Attendance Auto Generate Debug] Skipped due to exception', { dateKey, type: exception.type });
        return; // Don't generate for this date
      }

      // If rescheduled, the original date is skipped.
      if (exception && exception.type === 'rescheduled') {
        skippedBecauseException = true;
        return;
      }

      // 2. Check if attendance already exists
      const existing = await this.repo.getAllOnce<EntityRecord & ClassPlanAttendance>('attendance', currentUser, undefined, [
        where('classPlanId', '==', classPlan.id),
        where('dateKey', '==', dateKey)
      ]);

      if (existing && existing.length > 0) {
        alreadyExists = true;
        return; // Skip creation
      }

      // 3. Prepare default statuses
      const studentStatus = classPlan.autoMarkStudentsPresent ? 'present' : 'absent';
      const staffStatus = classPlan.autoMarkStaffPresent ? 'present' : 'absent';

      const studentsData = (classPlan.studentIds || []).map((id, index) => ({
        studentId: id,
        studentName: classPlan.studentNames?.[index] || 'Unknown',
        status: studentStatus as any,
        markedBy: classPlan.autoGenerateAttendance ? 'system' : currentUser.uid,
        markedAt: new Date().toISOString()
      }));

      const staffData = (classPlan.assignedStaffIds || []).map((id, index) => ({
        staffId: id,
        staffName: classPlan.assignedStaffNames?.[index] || 'Unknown',
        role: 'teacher',
        status: staffStatus as any,
        markedBy: classPlan.autoGenerateAttendance ? 'system' : currentUser.uid,
        markedAt: new Date().toISOString()
      }));

      // 4. Create attendance
      const attendanceDoc: Partial<ClassPlanAttendance> = {
        organizationId: classPlan.organizationId,
        madrasaId: classPlan.madrasaId,
        classPlanId: classPlan.id!,
        courseId: classPlan.courseId,
        courseName: classPlan.courseName,
        classId: classPlan.classId,
        className: classPlan.className,
        date: date.toISOString(),
        dateKey: dateKey,
        startTime: classPlan.startTime,
        endTime: classPlan.endTime,
        type: 'class',
        status: 'draft',
        studentIds: classPlan.studentIds || [],
        staffIds: classPlan.assignedStaffIds || [],
        students: studentsData,
        staff: staffData,
        autoGenerated: true
      };

      await this.repo.create('attendance', attendanceDoc as any, currentUser);

      console.log('[Attendance Auto Generate Debug]', {
        classPlanId: classPlan.id,
        classId: classPlan.classId,
        date,
        dateKey,
        studentCount: studentsData.length,
        staffCount: staffData.length,
        skippedBecauseException,
        alreadyExists,
      });

    } catch (error: any) {
      console.error('[Attendance Auto Generate Failed]', {
        classPlanId: classPlan?.id,
        classId: classPlan?.classId,
        date,
        errorCode: error?.code,
        errorMessage: error?.message,
        error,
      });
      throw error;
    }
  }

  formatDateKey(date: Date): string {
    return formatDate(date, 'yyyy-MM-dd', 'en-US');
  }

  isDateInPlan(classPlan: ClassPlan, date: Date): boolean {
    const dateKey = this.formatDateKey(date);
    const dayOfWeek = date.toLocaleDateString('en-US', { weekday: 'long' }).toLowerCase();

    if (classPlan.status !== 'active') return false;

    const planStart = new Date(classPlan.startDate);
    planStart.setHours(0, 0, 0, 0);
    const checkDate = new Date(date);
    checkDate.setHours(0, 0, 0, 0);

    if (checkDate < planStart) return false;
    if (classPlan.endDate) {
      const planEnd = new Date(classPlan.endDate);
      planEnd.setHours(0, 0, 0, 0);
      if (checkDate > planEnd) return false;
    }

    if (classPlan.scheduleType === 'oneTime') {
      return this.formatDateKey(planStart) === dateKey;
    }

    if (classPlan.scheduleType === 'weekly') {
      return (classPlan.weekDays || []).includes(dayOfWeek);
    }

    if (classPlan.scheduleType === 'monthly') {
      return checkDate.getDate() === planStart.getDate();
    }

    if (classPlan.scheduleType === 'customDates') {
      return (classPlan.selectedDates || []).includes(dateKey);
    }

    return false;
  }
}
